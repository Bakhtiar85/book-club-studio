"""Point the Remotion app at an episode. Usage: python tools/use_episode.py <episode>"""
import shutil, sys
from common import APP, find_episode

def use(ref):
    ep = find_episode(ref)
    data = ep / "data"
    if not (data / "lines.json").exists():
        sys.exit(f"{ep.name}: no voice data yet — run: python tools/voice.py {ep.name[:3]}")
    scenes = APP / "src" / "episodes" / ep.name / "scenes.tsx"
    if not scenes.exists():
        sys.exit(f"Missing {scenes} — every episode needs its scenes file.")
    cur = APP / "src" / "current"; cur.mkdir(exist_ok=True)
    for f in ("lines.json", "words.json", "mouth.json"):
        shutil.copy(data / f, cur / f)
    from common import load_json
    book = (load_json(ep / "script.json").get("source") or {}).get("book")
    world = APP / "src" / "books" / (book or "") / "world.tsx"
    if not book or not world.exists():
        sys.exit(f"script.json source.book must name a folder in app/src/books/ that has world.tsx (got '{book}')")
    (cur / "book.ts").write_text(f'// GENERATED by tools/use_episode.py — do not edit by hand.\nexport {{ CharacterSheet, BookProp }} from "../books/{book}/world";\n', encoding="utf-8")
    (cur / "index.ts").write_text(f'// GENERATED by tools/use_episode.py — do not edit by hand.\nexport {{ SCENES }} from "../episodes/{ep.name}/scenes";\n', encoding="utf-8")
    print(f"App now shows episode {ep.name}")
    return ep

if __name__ == "__main__":
    use(sys.argv[1] if len(sys.argv) > 1 else "latest")
