"""Where are we? Usage: python tools/status.py  (also rewrites series/EPISODES.md)"""
import datetime, re
from common import EPISODES, SERIES, load_json

def main():
    brief = "--brief" in __import__("sys").argv
    rows = []
    for ep in sorted(p for p in EPISODES.iterdir() if p.is_dir() and re.match(r"^\d{3}-", p.name)):
        m = load_json(ep / "episode.json") if (ep / "episode.json").exists() else {}
        s = load_json(ep / "script.json") if (ep / "script.json").exists() else {}
        r = m.get("results", {})
        rows.append([ep.name[:3], s.get("book", ""), s.get("part", ""), m.get("status", "?"), m.get("published_on", ""),
                     str(r.get("views", "")), f"{r.get('vote_noor', '')}/{r.get('vote_baba', '')}" if r else "", m.get("url", "")])
    hdr = ["#", "Book", "Part", "Status", "Published", "Views", "Votes N/B", "URL"]
    md = "# Episode log (generated by tools/status.py — edit episode.json files, not this)\n\n"
    md += "| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr) + "\n"
    md += "".join("| " + " | ".join(r) + " |\n" for r in rows)
    (SERIES / "EPISODES.md").write_text(md, encoding="utf-8")
    if brief:
        from remind import summary
        print("[Book Club status]\n" + summary()); return
    print(md)
    pub = [r[4] for r in rows if r[4]]
    if pub:
        last = max(datetime.date.fromisoformat(d) for d in pub)
        days = (datetime.date.today() - last).days
        print(f"Last published: {last} ({days} day{'s' if days != 1 else ''} ago)" + ("  <- time for the next one!" if days >= 4 else ""))
    else:
        print("Nothing published yet.")
    pending = [r for r in rows if r[3] in ("rendered",)]
    if pending:
        print("Rendered but not published: " + ", ".join(r[0] for r in pending))

if __name__ == "__main__":
    main()
